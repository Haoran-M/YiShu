import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=p=>readFile(root+p,'utf8');
const corpus=JSON.parse(await read('sites/yishu/dist/assets/hexagrams.json'));
const rows=(await read('tools/english-gua.txt')).trim().split(/\r?\n/);
const chinese=(await read('tools/chinese-gua.txt')).trim().split(/\r?\n/).map(row=>{const [meaning,reflection]=row.split('|');return {meaning,reflection};});
if(chinese.length!==64||chinese.some(row=>!row.meaning||!row.reflection)) throw new Error('Incomplete Chinese explanations');
if(rows.length!==64) throw new Error('Expected 64 English gua');
const english=rows.map((row,index)=>{
  const [pinyin,name,meaning,image,reflection,notes]=row.split('|');
  const lines=notes?.split(/;(?=\S)/);
  if(!meaning||!reflection||lines?.length!==6) throw new Error('Incomplete gua '+(index+1));
  return {number:index+1,pinyin,name,meaning,image,reflection,lines,chinese:chinese[index],
    ...(index===0?{extra:'When all six lines change, the image of dragons without a single dominating head suggests shared strength without overbearing leadership.'}:{}),
    ...(index===1?{extra:'When all six lines change, remain faithful to an enduring, receptive commitment.'}:{})};
});
const ui=Object.fromEntries((await read('tools/english-ui.txt')).trimEnd().split(/\r?\n/).filter(row=>row.trim()).map(row=>{
  const i=row.indexOf('='); if(i<1) throw new Error('Invalid UI entry: '+row);return [row.slice(0,i),row.slice(i+1)];
}));
const classical={};
const chineseNumbers=['一','二','三','四','五','六','七','八','九','十','冬','腊'];
for(let n=1;n<=30;n++){
  const label=n===10?'初十':n===20?'二十':n===30?'三十':(n<10?'初':n<20?'十':'廿')+chineseNumbers[(n-1)%10];
  ui[label]='Day '+n;
}
for(let n=1;n<=12;n++){ui[chineseNumbers[n-1]+'月']='Month '+n;ui['闰'+chineseNumbers[n-1]+'月']='Leap month '+n;}
ui['正月']='Month 1';
for(const [i,h] of corpus.entries()){
  const e=english[i];
  ui[h.title]=`${e.name} · ${e.pinyin}`;
  // Names are disambiguated by full title in lists and reading figures.
  classical[h.judgment]=e.meaning;
  classical[h.image]=e.image;
  h.lines.forEach((line,n)=>classical[line]=`Line ${n+1}: ${e.lines[n]}`);
  if(h.extra) classical[h.extra]=e.extra;
}
const payload={ui,classical,hexagrams:english};
await writeFile(root+'sites/yishu/dist/assets/english.json',JSON.stringify(payload,null,2)+'\n');
await writeFile(root+'app/src/main/assets/english.json',JSON.stringify(payload,null,2)+'\n');
await writeFile(root+'sites/yishu/dist/english.js','// Generated by tools/build-english.mjs. Edit tools/english-*.txt.\nexport const english = '+JSON.stringify(payload)+';\n'+`
const pieces=Object.keys(english.ui).sort((a,b)=>b.length-a.length);
export function englishText(value){
  const text=String(value??'');
  if(Object.hasOwn(english.ui,text)) return english.ui[text];
  if(!/\\p{Script=Han}/u.test(text)) return text;
  return text.replace(new RegExp(pieces.map(s=>s.replace(/[.*+?^\u0024{}()|[\\]\\\\]/g,'\\\\\u0024&')).join('|'),'gu'),m=>english.ui[m]);
}
`);
console.log(`Built ${english.length} English gua, ${Object.keys(classical).length} classical paraphrases, and ${Object.keys(ui).length} interface entries.`);
